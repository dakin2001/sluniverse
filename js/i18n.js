const AVAILABLE_LANGUAGES = ['English', 'Français', 'Español', 'Português', 'ไทย', 'Filipino', 'Bahasa Indonesia', 'Tiếng Việt'];

/**
 * Applies the given language's translations to every element with a data-i18n attribute.
 * Falls back to English for any missing key.
 */
let currentLang = 'English';

/**
 * Returns the translated string for `key` in the currently active language.
 * Falls back to English, then to the key itself if truly missing.
 * Usable directly inside JS template strings, not just static HTML.
 */
function t(key){
  const dict = I18N[currentLang] || I18N.English;
  return dict[key] || I18N.English[key] || key;
}

function applyLanguage(lang){
  currentLang = I18N[lang] ? lang : 'English';
  try { localStorage.setItem('slu_lang', currentLang); } catch (e){ /* private browsing, ignore */ }
  const dict = I18N[currentLang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    let text = dict[key] || I18N.English[key];
    if (!text) return;
    if (key === 'empty_guides'){
      text = text.replace('%CREATE%', `<strong>+ ${dict.create_guide || I18N.English.create_guide}</strong>`);
      el.innerHTML = text;
    } else {
      el.textContent = text;
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = dict[key] || I18N.English[key] || el.placeholder;
  });
}

/**
 * Applies whatever language was last used on this device, immediately, from local
 * cache, without waiting for Firebase. Prevents the English-then-translated flash
 * on page load. Call this as early as possible, then call applyLanguage(profile.language)
 * again once the real profile loads, in case it changed on another device.
 */
function applyCachedLanguageInstantly(){
  try {
    const cached = localStorage.getItem('slu_lang');
    if (cached) applyLanguage(cached);
  } catch (e){ /* private browsing, ignore */ }
}
